-- Выполняется автоматически только при первом создании Docker volume.
-- Повторный запуск безопасен для данных, но не заменяет миграции при изменении схемы.
CREATE TABLE IF NOT EXISTS clients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(name)) > 0),
    phone VARCHAR(16) NOT NULL UNIQUE,
    address VARCHAR(300) NOT NULL CHECK (LENGTH(TRIM(address)) > 0)
);

CREATE TABLE IF NOT EXISTS technicians (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(name)) > 0),
    phone VARCHAR(16) NOT NULL UNIQUE,
    specialization VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(specialization)) > 0)
);

CREATE TABLE IF NOT EXISTS repair_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
    technician_id INTEGER REFERENCES technicians(id) ON DELETE RESTRICT,
    appliance_type VARCHAR(100) NOT NULL CHECK (LENGTH(TRIM(appliance_type)) > 0),
    brand VARCHAR(100) NOT NULL CHECK (LENGTH(TRIM(brand)) > 0),
    model VARCHAR(100) NOT NULL CHECK (LENGTH(TRIM(model)) > 0),
    problem VARCHAR(2000) NOT NULL CHECK (LENGTH(TRIM(problem)) > 0),
    created_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'NEW'
        CHECK (status IN ('NEW', 'DIAGNOSING', 'WAITING_PARTS', 'IN_REPAIR', 'COMPLETED', 'CANCELLED')),
    cost NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    CHECK ((status = 'COMPLETED' AND completed_at IS NOT NULL AND completed_at >= created_at)
        OR (status <> 'COMPLETED' AND completed_at IS NULL)),
    CHECK (status IN ('NEW', 'CANCELLED') OR technician_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_requests_client ON repair_requests(client_id);
CREATE INDEX IF NOT EXISTS idx_requests_technician ON repair_requests(technician_id);
CREATE INDEX IF NOT EXISTS idx_requests_status ON repair_requests(status);
CREATE INDEX IF NOT EXISTS idx_requests_created ON repair_requests(created_at);
